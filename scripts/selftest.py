#!/usr/bin/env python3
"""selftest.py — one-command end-to-end self-test for the academic-slides skill.

Generates a tiny synthetic case (template pptx + material.json + workorder + a
PIL-drawn figure) inside a fresh temp dir — nothing is bundled or pre-baked —
then runs the real pipeline scripts against it and verifies the deliverables.

Usage: python3 selftest.py [--keep]   (prints SELFTEST_OK or SELFTEST_FAIL)
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
PY = sys.executable


def make_figure(path: Path):
    from PIL import Image, ImageDraw

    img = Image.new("RGB", (640, 400), "white")
    dr = ImageDraw.Draw(img)
    dr.line([(60, 340), (600, 340)], fill="black", width=2)
    dr.line([(60, 340), (60, 40)], fill="black", width=2)
    pts = [(60 + i * 70, 340 - v * 3) for i, v in enumerate([12, 18, 25, 31, 36, 40, 43, 45])]
    dr.line(pts, fill="#2b6cb0", width=3)
    for p in pts:
        dr.ellipse([p[0] - 4, p[1] - 4, p[0] + 4, p[1] + 4], fill="#2b6cb0")
    dr.text((70, 30), "ROUGE-1 vs epoch (demo figure)", fill="black")
    img.save(str(path))


def make_template(path: Path):
    from pptx import Presentation
    from pptx.util import Emu

    prs = Presentation()
    prs.slide_width = Emu(int(13.333 * 914400))
    prs.slide_height = Emu(int(7.5 * 914400))
    prs.save(str(path))


def build_case(root: Path):
    (root / "inputs" / "figures").mkdir(parents=True, exist_ok=True)
    (root / "artifacts").mkdir(parents=True, exist_ok=True)
    (root / "work").mkdir(parents=True, exist_ok=True)
    (root / "output").mkdir(parents=True, exist_ok=True)
    make_figure(root / "inputs" / "figures" / "fig_demo.png")
    make_template(root / "inputs" / "target-template.pptx")
    (root / "case.json").write_text(json.dumps(
        {"case_id": "SELFTEST-001", "kind": "generated by selftest.py"}), encoding="utf-8")
    quote = "门控稀疏率由浅层表示预测每个 token 的稀疏率"
    (root / "material.json").write_text(json.dumps({
        "title": "自适应稀疏注意力 ASA（自测材料）",
        "sections": {"method": quote + "，重要内容保留更大窗口。"},
        "key_numbers": {"rouge1": "45.6", "latency_ms": "236"},
        "figures": [{"id": "图D", "file": "figures/fig_demo.png",
                      "caption": "自测演示图：收敛曲线"}],
    }, ensure_ascii=False), encoding="utf-8")
    (root / "artifacts" / "slide-workorder.json").write_text(json.dumps({
        "mode": "create", "slide_count": 3, "audience": "自测", "language": "zh",
        "template": "inputs/target-template.pptx",
    }, ensure_ascii=False), encoding="utf-8")
    plan = {
        "deck_title": "自适应稀疏注意力 ASA（自测）", "mode": "create",
        "rationale": "自测用最小三页结构：标题、方法+图、总结。",
        "slides": [
            {"role": "title", "layout_hint": "title", "title": "自适应稀疏注意力 ASA（自测）",
             "subtitle": "selftest 生成", "notes": "自测标题页。"},
            {"role": "method", "layout_hint": "content", "title": "方法与演示图",
             "bullets": [{"t": "门控稀疏率：token 级动态窗口", "lvl": 0},
                          {"t": "ArXiv-Long 上 ROUGE-1 45.6", "lvl": 0}],
             "image": {"path": str(root / "inputs" / "figures" / "fig_demo.png"),
                        "ref": "图D", "caption": "自测演示图：收敛曲线"},
             "notes": "结合演示图讲方法。",
             "sources": [{"ref": "图D", "locator": "material.sections",
                           "quote": quote}]},
            {"role": "summary", "layout_hint": "content", "title": "总结",
             "bullets": [{"t": "8k token 延迟 236ms", "lvl": 0}],
             "notes": "自测总结页。",
             "sources": [{"ref": "数字", "locator": "material.key_numbers", "quote": "236"}]},
        ],
        "uncertainty": [],
    }
    (root / "work" / "slides_plan.json").write_text(
        json.dumps(plan, ensure_ascii=False, indent=1), encoding="utf-8")


def run(script: str, args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run([PY, str(SCRIPTS / script), *args],
                          capture_output=True, text=True, timeout=300)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--keep", action="store_true", help="keep temp dir for inspection")
    args = ap.parse_args()
    root = Path(tempfile.mkdtemp(prefix="slides_selftest_"))
    build_case(root)
    steps = [
        ("inspect_case.py", ["--case-dir", str(root), "--work", str(root / "work")]),
        ("build_deck.py", ["--plan", str(root / "work" / "slides_plan.json"),
                            "--work", str(root / "work"),
                            "--out", str(root / "output" / "presentation.pptx")]),
        ("check_deck.py", ["--deck", str(root / "output" / "presentation.pptx"),
                            "--work", str(root / "work")]),
        ("export_preview.py", ["--deck", str(root / "output" / "presentation.pptx"),
                                "--work", str(root / "work"),
                                "--pdf", str(root / "output" / "presentation.pdf")]),
        ("assemble_result.py", ["--case-dir", str(root), "--work", str(root / "work"),
                                 "--deck", str(root / "output" / "presentation.pptx"),
                                 "--status", "auto"]),
    ]
    failures = []
    for script, sargs in steps:
        r = run(script, sargs)
        tail = (r.stdout or "").strip().splitlines()[-1:] or [f"rc={r.returncode} {r.stderr[:200]}"]
        print(f"[selftest] {script}: {tail[0][:200]}")
        if r.returncode != 0 or any(k in (r.stdout or "") for k in ("_FAILED", "_ISSUES")):
            failures.append((script, tail[0][:200]))
    result = root / "output" / "result.json"
    ok = result.is_file()
    if ok:
        rj = json.loads(result.read_text(encoding="utf-8"))
        need = ["case_id", "status", "editable_source", "export_artifact",
                "content_map", "compliance_checks", "exceptions"]
        missing = [f for f in need if f not in rj]
        if missing:
            failures.append(("result.json", f"missing {missing}"))
        if rj.get("status") not in ("ok", "partial"):
            failures.append(("status", str(rj.get("status"))))
    else:
        failures.append(("result.json", "not produced"))
    print(f"[selftest] temp dir: {root}" + (" (kept)" if args.keep else ""))
    if failures:
        print("SELFTEST_FAIL " + json.dumps(failures, ensure_ascii=False))
        return 1
    print("SELFTEST_OK all steps green, result.json contract complete")
    if not args.keep:
        shutil.rmtree(root, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
