#!/usr/bin/env python3
"""selftest.py — one-command dual-mode (create + edit) end-to-end self-test.

Generates tiny synthetic cases (template pptx + material.json + PDF with vector
figure + workorder + PIL figure + starting deck) inside a fresh temp dir —
nothing is pre-baked — then runs the full pipeline in BOTH create and edit
modes and verifies deliverables, checks, and per-slide diffs.

Usage: python3 selftest.py [--keep]   (prints SELFTEST_OK or SELFTEST_FAIL)
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
PY = sys.executable


def make_figure(path: Path):
    from PIL import Image, ImageDraw

    img = Image.new("RGB", (640, 400), "white")
    dr = ImageDraw.Draw(img)
    dr.line([(60, 340), (600, 340)], fill="black", width=2)
    dr.line([(60, 340), (60, 40)], fill="black", width=2)
    pts = [(60 + i * 70, 340 - v * 3) for i, v in enumerate([12, 18, 25, 31, 36, 40, 43, 45])]
    dr.line(pts, fill="#2b6cb0", width=3)
    for p in pts:
        dr.ellipse([p[0] - 4, p[1] - 4, p[0] + 4, p[1] + 4], fill="#2b6cb0")
    dr.text((70, 30), "ROUGE-1 vs epoch (demo figure)", fill="black")
    img.save(str(path))


def make_template(path: Path):
    from pptx import Presentation
    from pptx.util import Emu

    prs = Presentation()
    prs.slide_width = Emu(int(13.333 * 914400))
    prs.slide_height = Emu(int(7.5 * 914400))
    prs.save(str(path))


def make_starting_deck(path: Path):
    from pptx import Presentation
    from pptx.util import Emu

    prs = Presentation()
    prs.slide_width = Emu(int(13.333 * 914400))
    prs.slide_height = Emu(int(7.5 * 914400))
    s1 = prs.slides.add_slide(prs.slide_layouts[0])
    s1.shapes.title.text = "Old Title Placeholder"
    s2 = prs.slides.add_slide(prs.slide_layouts[1])
    s2.shapes.title.text = "Method Overview"
    p = s2.placeholders[1].text_frame.paragraphs[0]
    r = p.add_run()
    r.text = "OldMethod achieves 41.2 ROUGE-1."
    r.font.name = "Arial"  # pre-existing starting-deck font (must not false-fail edit check!)
    s3 = prs.slides.add_slide(prs.slide_layouts[1])
    s3.shapes.title.text = "Preliminary Results"
    s3.placeholders[1].text = "To be replaced with final results."
    prs.save(str(path))


